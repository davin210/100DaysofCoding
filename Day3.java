public class day3 {
public static void main(String[] args) {
    System.out.println("nama :\n");
    // \n berfungsi untuk menambah line
    System.out.println("nama :\t");
    // \t berfungsi untuk menambah tab
    System.out.println("nama :\"");
    // \" berfungsi untuk menampilkan tanda " itu sendiri
    System.out.println("nama :\\");
    // \\ berfungsi untuk menampilkan tanda \ itu sendiri
    System.out.println("nama :\r");
    // \r berfungsi untuk mewakilkan baris baru
    System.out.println("nama :\'");
    // \' berfungsi untuk meyisipkan tanda '
    System.out.println("nama :\f");
    // \f berfungsi untuk mrnyisipkan form feed
    System.out.println("nama :\b");
    // \b berfungsi untuk backspace
    }
    
}
