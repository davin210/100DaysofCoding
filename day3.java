public class App {
    public static void main(String[] args) throws Exception {
        String Nama = "Davin";

        System.out.printf("Nama :%s\n",Nama);
        System.out.printf("Nama :%s\t",Nama);
        System.out.printf("Nama :%s\"",Nama);
        System.out.printf("Nama :%s\\",Nama);
        /**
         * \n membuat baris baru
         * \t memberikan spasi selbar tab
         * \" menampilkan tanda kutip ganda
         * \\ menampilkan garis miring itu sendiri
         */
    }
}
